import test from 'node:test';
import assert from 'node:assert/strict';
import { createVisitorHandler } from './visitors.js';
import { JSDOM } from 'jsdom';
import { readFile } from 'node:fs/promises';
const id = '12345678-1234-4234-9234-123456789abc';
const req = body => ({ method: 'POST', headers: { origin: 'https://example.com', host: 'example.com' }, body });
test('visitor aggregation uses atomic shared Redis, hashes identity and rejects foreign or invalid requests', async t => {
    const oldUrl = process.env.VISITOR_REDIS_REST_URL, oldToken = process.env.VISITOR_REDIS_REST_TOKEN;
    process.env.VISITOR_REDIS_REST_URL = 'https://example.upstash.io'; process.env.VISITOR_REDIS_REST_TOKEN = 'test-only';
    t.after(() => { if (oldUrl === undefined) delete process.env.VISITOR_REDIS_REST_URL; else process.env.VISITOR_REDIS_REST_URL = oldUrl; if (oldToken === undefined) delete process.env.VISITOR_REDIS_REST_TOKEN; else process.env.VISITOR_REDIS_REST_TOKEN = oldToken; });
    let commands;
    const handler = createVisitorHandler(async (url, options) => { commands = JSON.parse(options.body); assert.equal(options.headers.Authorization, 'Bearer test-only'); return Response.json({ result: [2, 10] }); }, () => 100000);
    const result = await handler(req({ visitorId: id }));
    assert.equal(result.status, 200); assert.equal(result.body.online, 2); assert.equal(result.body.total, 10);
    assert.equal(commands[0], 'EVAL'); assert.match(commands[1], /SADD/); assert.match(commands[1], /ZREMRANGEBYSCORE/);
    assert.equal(commands[2], '2'); assert.equal(commands[5].length, 64); assert.ok(!JSON.stringify(result).includes(id));
    await handler({ method: 'GET', headers: {} }); assert.equal(commands[5], '');
    assert.equal((await handler(req({ visitorId: 'invalid' }))).status, 400);
    assert.equal((await handler({ ...req({ visitorId: id }), headers: { origin: 'https://evil.test', host: 'example.com' } })).status, 403);
    assert.equal((await handler(req('x'.repeat(1025)))).status, 400);
    assert.equal((await createVisitorHandler(async () => Response.json({ error: 'WRONGPASS' }))(req({ visitorId: id }))).status, 503);
});
test('visitor UI preserves browser identity on reload, refreshes presence, and never displays fabricated counts on failure', async t => {
    const html = await readFile(new URL('./public/index.html', import.meta.url), 'utf8');
    const script = await readFile(new URL('./public/visitors.js', import.meta.url), 'utf8');
    const dom = new JSDOM(html, { url: 'https://example.com', runScripts: 'outside-only' });
    t.after(() => dom.window.close());
    Object.defineProperty(dom.window.document, 'hidden', { value: false });
    dom.window.localStorage.setItem('trend-radar-visitor-id-v1', id);
    const sent = []; let tick, fail = false;
    dom.window.setInterval = callback => { tick = callback; return 1; }; dom.window.clearInterval = () => {};
    dom.window.fetch = async (url, options) => { sent.push(JSON.parse(options.body)); return { ok: !fail, json: async () => ({ online: 1, total: 123 }) }; };
    dom.window.eval(script); await new Promise(resolve => setImmediate(resolve));
    assert.equal(sent[0].visitorId, id); assert.equal(dom.window.document.getElementById('totalVisitors').textContent, '123');
    await tick(); assert.equal(sent[1].visitorId, id);
    fail = true; await tick(); assert.equal(dom.window.document.getElementById('totalVisitors').textContent, '—');
    assert.equal(dom.window.localStorage.getItem('trend-radar-visitor-id-v1'), id);
});
